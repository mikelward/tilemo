-- Writes hammerspoon/tide/compose.tsv from libX11's en_US.UTF-8 Compose
-- file, the table Linux's Compose key reads: each Multi_key sequence typed
-- with printable ASCII keys, and what it types. Sequences through dead keys,
-- or keys beyond ASCII, are left out, since a Mac keyboard can't send them
-- the same way.
--
--   lua ci/compose_table.lua /usr/share/X11/locale/en_US.UTF-8/Compose \
--       > hammerspoon/tide/compose.tsv

local NAMED = {
    space = " ", exclam = "!", quotedbl = '"', numbersign = "#", dollar = "$",
    percent = "%", ampersand = "&", apostrophe = "'", parenleft = "(",
    parenright = ")", asterisk = "*", plus = "+", comma = ",", minus = "-",
    period = ".", slash = "/", colon = ":", semicolon = ";", less = "<",
    equal = "=", greater = ">", question = "?", at = "@", bracketleft = "[",
    backslash = "\\", bracketright = "]", asciicircum = "^", underscore = "_",
    grave = "`", braceleft = "{", bar = "|", braceright = "}", asciitilde = "~",
}

local function key(name)
    if NAMED[name] then
        return NAMED[name]
    end
    if name:match("^[%w]$") then
        return name
    end
end

local path = assert(arg[1], "usage: lua ci/compose_table.lua COMPOSE_FILE")
local seen, rows = {}, {}
-- The quoted string after the colon, its escapes undone.
local function quoted(rest)
    local i = rest:find('"', 1, true)
    if not i then
        return nil
    end
    local out = {}
    i = i + 1
    while i <= #rest do
        local c = rest:sub(i, i)
        if c == "\\" then
            out[#out + 1] = rest:sub(i + 1, i + 1)
            i = i + 2
        elseif c == '"' then
            return table.concat(out)
        else
            out[#out + 1] = c
            i = i + 1
        end
    end
end

for line in io.lines(path) do
    local keys, rest = line:match("^<Multi_key>%s*([^:]-)%s*:(.*)$")
    local out = rest and quoted(rest)
    if keys and out and out ~= "" then
        local seq = {}
        for name in keys:gmatch("<([^>]+)>") do
            local k = key(name)
            if not k then
                seq = nil
                break
            end
            seq[#seq + 1] = k
        end
        if seq and #seq > 0 then
            local s = table.concat(seq)
            if not seen[s] and not s:find("\t") and not out:find("[\t\n]") then
                seen[s] = true
                rows[#rows + 1] = s .. "\t" .. out
            end
        end
    end
end
io.write("# Linux's Compose sequences (tide SPEC.md §10): the keys after Compose,\n")
io.write("# then what they type. Generated by ci/compose_table.lua from libX11's\n")
io.write("# en_US.UTF-8 Compose file (LICENSE-X11). Don't edit; regenerate.\n")
for _, r in ipairs(rows) do
    io.write(r, "\n")
end
