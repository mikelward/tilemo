local t = require("t")
local attention = require("timo.attention")

t.test("a title's unread count is read from parentheses", function()
    t.eq(attention.count("Chat (3)"), 3)
    t.eq(attention.count("(12) Inbox"), 12)
    t.eq(attention.count("Inbox"), 0)
end)

t.test("a rising title count marks the window; a falling one doesn't", function()
    local a = attention.new()
    a:title(1, "app", "Chat")
    t.eq(#a:list(), 0)
    a:title(1, "app", "Chat (2)")
    t.eq(a:list()[1].id, 1)
    a:focused(1, "app")
    a:title(1, "app", "Chat (1)")
    t.eq(#a:list(), 0)
end)

t.test("a Dock badge appearing or rising marks the app", function()
    local a = attention.new()
    a:badge("com.example.mail", "")
    a:badge("com.example.mail", "3")
    t.eq(a:list()[1].app, "com.example.mail")
    a:focused(9, "com.example.mail")
    t.eq(#a:list(), 0)
    a:badge("com.example.mail", "•")
    t.eq(#a:list(), 0, "a dot after a count isn't more")
end)

t.test("the most recent mark comes first, and a repeat moves it up", function()
    local a = attention.new()
    a:title(1, "x", "a (1)")
    a:title(2, "y", "b (1)")
    t.eq(a:list()[1].id, 2)
    a:title(1, "x", "a (2)")
    t.eq(a:list()[1].id, 1)
    t.eq(#a:list(), 2)
end)

t.test("a window that goes away takes its marks with it", function()
    local a = attention.new()
    a:title(1, "x", "a (1)")
    a:gone(1)
    t.eq(#a:list(), 0)
end)

t.test("an app that leaves the Dock's badges starts over", function()
    local att = attention.new()
    att:dock({ { app = "chat", label = "5" } })
    att:focused(1, "chat")
    att:dock({}) -- quit
    att:dock({ { app = "chat", label = "1" } }) -- back, with a new badge
    t.eq(#att:list(), 1)
end)

t.done("attention")
