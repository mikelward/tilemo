local t = require("t")
local attention = require("tide.attention")

t.test("a notification marks its app until you focus one of its windows", function()
    local a = attention.new()
    a:notified("com.example.mail")
    t.eq(a:list()[1].app, "com.example.mail")
    t.eq(a:list()[1].kind, "app")
    a:focused(9, "com.example.mail")
    t.eq(#a:list(), 0)
end)

t.test("a bell marks its window until you focus it", function()
    local a = attention.new()
    a:rang(1, "kitty")
    t.eq(a:list()[1].id, 1)
    a:focused(2, "other")
    t.eq(#a:list(), 1, "another app's focus leaves it")
    a:focused(1, "kitty")
    t.eq(#a:list(), 0)
end)

t.test("a browser's notifications from two sites are two marks", function()
    local a = attention.new()
    a:notified("com.google.Chrome", "mail.example.com")
    a:notified("com.google.Chrome", "chat.example.com")
    a:notified("com.google.Chrome", "mail.example.com")
    t.eq(#a:list(), 2)
    t.eq(a:list()[1].site, "mail.example.com", "a repeat moves it up")
end)

t.test("the most recent mark comes first, and a repeat moves it up", function()
    local a = attention.new()
    a:rang(1, "x")
    a:rang(2, "y")
    t.eq(a:list()[1].id, 2)
    a:rang(1, "x")
    t.eq(a:list()[1].id, 1)
    t.eq(#a:list(), 2)
end)

t.test("a window that goes away takes its marks with it", function()
    local a = attention.new()
    a:rang(1, "x")
    a:gone(1)
    t.eq(#a:list(), 0)
end)

t.test("a site's notification clears only with a window on that site", function()
    local a = attention.new()
    a:notified("com.google.Chrome", "mail.example.com")
    a:focused(3, "com.google.Chrome", "chat.example.com")
    t.eq(#a:list(), 1, "Chat's window leaves Mail's mark")
    a:focused(3, "com.google.Chrome", nil)
    t.eq(#a:list(), 1, "nor does a window whose tab isn't known")
    a:focused(2, "com.google.Chrome", "mail.example.com")
    t.eq(#a:list(), 0)
end)

t.done("attention")
